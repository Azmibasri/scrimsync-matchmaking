
-- 1. Tabel Pengguna (Master Akun: Pemain/Kapten & Admin)
CREATE TABLE Pengguna (
    id_pengguna     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR2(50)  NOT NULL UNIQUE,
    email           VARCHAR2(100) NOT NULL UNIQUE,
    password_hash   VARCHAR2(255) NOT NULL,
    role_sistem     VARCHAR2(20)  DEFAULT 'PEMAIN' NOT NULL,
    cooldown_hingga DATE,
    dibuat_pada     DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT chk_pengguna_role CHECK (role_sistem IN ('PEMAIN', 'ADMIN'))
);

-- 2. Tabel Profil_Game_Role (Role Bermain & MMR Aktif)
CREATE TABLE Profil_Game_Role (
    id_profil       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pengguna     NUMBER        NOT NULL,
    nama_game       VARCHAR2(50)  DEFAULT 'Mobile Legends' NOT NULL,
    role_utama      VARCHAR2(30)  NOT NULL,
    mmr_aktif       NUMBER(6)     DEFAULT 1000 NOT NULL,
    diperbarui_pada DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_profil_pengguna FOREIGN KEY (id_pengguna) REFERENCES Pengguna(id_pengguna),
    CONSTRAINT uq_profil_user_role UNIQUE (id_pengguna, nama_game, role_utama),
    CONSTRAINT chk_profil_role CHECK (role_utama IN ('JUNGLER', 'SUPPORT', 'MID', 'GOLD', 'EXP')),
    CONSTRAINT chk_profil_mmr  CHECK (mmr_aktif >= 0)
);

-- 3. Tabel Antrean_Matchmaking (Target 1.000+ Data Uji & Composite Index)
CREATE TABLE Antrean_Matchmaking (
    id_antrean      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pengguna     NUMBER        NOT NULL,
    role_pilihan    VARCHAR2(30)  NOT NULL,
    mmr_saat_ini    NUMBER(6)     NOT NULL,
    status_antrean  VARCHAR2(20)  DEFAULT 'MENUNGGU' NOT NULL,
    masuk_pada      DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_antrean_pengguna FOREIGN KEY (id_pengguna) REFERENCES Pengguna(id_pengguna),
    CONSTRAINT chk_antrean_role   CHECK (role_pilihan IN ('JUNGLER', 'SUPPORT', 'MID', 'GOLD', 'EXP')),
    CONSTRAINT chk_antrean_status CHECK (status_antrean IN ('MENUNGGU', 'DIPASANGKAN', 'BATAL')),
    CONSTRAINT chk_antrean_mmr    CHECK (mmr_saat_ini >= 0)
);

-- 4. Tabel Sesi_Pertandingan (Lobby & Match Aktif)
CREATE TABLE Sesi_Pertandingan (
    id_sesi           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_season       VARCHAR2(20) DEFAULT 'S1-2026' NOT NULL,
    status_sesi       VARCHAR2(20) DEFAULT 'READY_CHECK' NOT NULL,
    kuota_maksimal    NUMBER(2)    DEFAULT 10 NOT NULL,
    rata_rata_mmr     NUMBER(6),
    batas_ready_check DATE         DEFAULT (SYSDATE + (1 / 1440)) NOT NULL,
    dibuat_pada       DATE         DEFAULT SYSDATE NOT NULL,
    CONSTRAINT chk_sesi_status CHECK (status_sesi IN ('READY_CHECK', 'BERLANGSUNG', 'SELESAI', 'DIBUBARKAN')),
    CONSTRAINT chk_sesi_kuota  CHECK (kuota_maksimal IN (2, 4, 6, 10))
);

-- 5. Tabel Partisipan_Match (Relasi Pemain di Dalam Sesi + Status Ready Check)
CREATE TABLE Partisipan_Match (
    id_partisipan     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sesi           NUMBER       NOT NULL,
    id_pengguna       NUMBER       NOT NULL,
    tim               VARCHAR2(10) NOT NULL,
    role_diambil      VARCHAR2(30) NOT NULL,
    status_konfirmasi VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    CONSTRAINT fk_part_sesi     FOREIGN KEY (id_sesi)     REFERENCES Sesi_Pertandingan(id_sesi),
    CONSTRAINT fk_part_pengguna FOREIGN KEY (id_pengguna) REFERENCES Pengguna(id_pengguna),
    CONSTRAINT uq_part_sesi_user UNIQUE (id_sesi, id_pengguna),
    CONSTRAINT chk_part_tim     CHECK (tim IN ('TIM_A', 'TIM_B')),
    CONSTRAINT chk_part_role    CHECK (role_diambil IN ('JUNGLER', 'SUPPORT', 'MID', 'GOLD', 'EXP')),
    CONSTRAINT chk_part_status  CHECK (status_konfirmasi IN ('PENDING', 'ACCEPTED', 'DECLINED'))
);

-- 6. Tabel Laporan_Skor (Bukti Hasil & Verifikasi Dispute Admin)
CREATE TABLE Laporan_Skor (
    id_laporan        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sesi           NUMBER        NOT NULL,
    id_pelapor        NUMBER        NOT NULL,
    tim_pemenang      VARCHAR2(10)  NOT NULL,
    bukti_url         VARCHAR2(255) NOT NULL,
    status_verifikasi VARCHAR2(20)  DEFAULT 'MENUNGGU' NOT NULL,
    diverifikasi_oleh NUMBER,
    dilaporkan_pada   DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_lap_sesi      FOREIGN KEY (id_sesi)           REFERENCES Sesi_Pertandingan(id_sesi),
    CONSTRAINT fk_lap_pelapor   FOREIGN KEY (id_pelapor)        REFERENCES Pengguna(id_pengguna),
    CONSTRAINT fk_lap_verif     FOREIGN KEY (diverifikasi_oleh) REFERENCES Pengguna(id_pengguna),
    CONSTRAINT chk_lap_pemenang CHECK (tim_pemenang IN ('TIM_A', 'TIM_B')),
    CONSTRAINT chk_lap_status   CHECK (status_verifikasi IN ('MENUNGGU', 'TERVERIFIKASI', 'DISPUTE'))
);

-- 7. Tabel Riwayat_MMR (Log Permanen Perubahan Poin - Dilindungi Trigger)
CREATE TABLE Riwayat_MMR (
    id_riwayat      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pengguna     NUMBER       NOT NULL,
    id_sesi         NUMBER       NOT NULL,
    kode_season     VARCHAR2(20) DEFAULT 'S1-2026' NOT NULL,
    mmr_lama        NUMBER(6)    NOT NULL,
    mmr_baru        NUMBER(6)    NOT NULL,
    selisih         NUMBER(6)    NOT NULL,
    dicatat_pada    DATE         DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_riw_pengguna FOREIGN KEY (id_pengguna) REFERENCES Pengguna(id_pengguna),
    CONSTRAINT fk_riw_sesi     FOREIGN KEY (id_sesi)     REFERENCES Sesi_Pertandingan(id_sesi)
);

-- 8. Tabel Log_Penalti (Log Permanen Dodge/AFK - Dilindungi Trigger)
CREATE TABLE Log_Penalti (
    id_penalti      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pengguna     NUMBER        NOT NULL,
    id_sesi         NUMBER,
    alasan          VARCHAR2(150) NOT NULL,
    durasi_menit    NUMBER(4)     DEFAULT 15 NOT NULL,
    dicatat_pada    DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_pen_pengguna FOREIGN KEY (id_pengguna) REFERENCES Pengguna(id_pengguna),
    CONSTRAINT fk_pen_sesi     FOREIGN KEY (id_sesi)     REFERENCES Sesi_Pertandingan(id_sesi),
    CONSTRAINT chk_pen_durasi  CHECK (durasi_menit > 0)
);